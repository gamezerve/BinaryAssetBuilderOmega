# Reborn: create namespace-valid SDK XML/W3X placeholders from MISSINGART entries; only exact old empty placeholders may be upgraded, never real artwork.
[CmdletBinding(SupportsShouldProcess,DefaultParameterSetName='File')]
param(
    [Parameter(Mandatory,ParameterSetName='File')][string]$LogPath,
    [Parameter(Mandatory,ParameterSetName='Text')][AllowEmptyString()][string]$LogText,
    [string]$SdkRoot
)
$ErrorActionPreference='Stop'
# Reborn: the same script works in repository/scripts and in a copied SDK/scripts folder.
if(-not $SdkRoot){
    $parent=Split-Path -Parent $PSScriptRoot
    $SdkRoot=if(Test-Path -LiteralPath (Join-Path $parent 'EALAModStudio.exe')){$parent}else{Join-Path $parent 'alpha'}
}
$sdk=[IO.Path]::GetFullPath($SdkRoot)
if(-not(Test-Path -LiteralPath $sdk -PathType Container)){throw ('SDK directory not found: '+$sdk)}
$art=[IO.Path]::GetFullPath((Join-Path $sdk 'Art')).TrimEnd([IO.Path]::DirectorySeparatorChar)
if($PSCmdlet.ParameterSetName-eq 'File'){$LogText=[IO.File]::ReadAllText((Resolve-Path -LiteralPath $LogPath).ProviderPath)}
# Reborn: consume only the quoted ART alias attached to MISSINGART, never arbitrary searched/source paths later in the log line.
$matches=[regex]::Matches($LogText,'(?im)\bWarning:\s*MISSINGART\s+[''"”]\s*(ART:[^''"”\r\n]+?)\s*[''"”]')
$seen=[Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$created=0;$existing=0;$skipped=0;$updated=0
# Reborn: default EA namespace makes an empty declaration a valid source envelope for XML and W3X includes.
$content='<?xml version="1.0" encoding="UTF-8"?><AssetDeclaration xmlns="uri:ea.com:eala:asset"></AssetDeclaration>'
$legacy='<?xml version="1.0" encoding="UTF-8"?><AssetDeclaration></AssetDeclaration>'
foreach($match in $matches){
    $reference=$match.Groups[1].Value.Trim()
    if(-not $seen.Add($reference)){continue}
    $relative=$reference.Substring(4).Replace('/',[IO.Path]::DirectorySeparatorChar).Replace('\',[IO.Path]::DirectorySeparatorChar)
    $parts=$relative.Split([IO.Path]::DirectorySeparatorChar)
    # Reborn: log text cannot redirect creation outside Art or name Windows devices/alternate streams.
    if([IO.Path]::IsPathRooted($relative)-or @($parts|Where-Object{$_-in @('','.','..')-or $_-match '[<>:"|?*\x00-\x1f]' -or $_-match '[. ]$' -or $_-match '^(?i:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)'}).Count){throw ('Invalid ART path in log: '+$reference)}
    if([IO.Path]::GetExtension($relative)-inotmatch '^\.(xml|w3x)$'){
        Write-Warning ('Skipped non-XML/W3X ART reference: '+$reference);$skipped++;continue
    }
    # Reborn: bare asset names use the SDK's two-character fanout; explicit subdirectories retain their authored relative path.
    if($parts.Length-eq 1){$relative=Join-Path $relative.Substring(0,[Math]::Min(2,$relative.Length)).ToUpperInvariant() $relative}
    $target=[IO.Path]::GetFullPath((Join-Path $art $relative))
    if(-not $target.StartsWith($art+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)){throw ('ART target escaped SDK directory: '+$reference)}
    # Reborn: refuse junction/symlink redirects before creating any directory or file; cloud placeholders are ordinary SDK content.
    for($part=Split-Path -Parent $target;$part;$part=Split-Path -Parent $part){
        if(Test-Path -LiteralPath $part){$item=Get-Item -LiteralPath $part -Force;if($item.LinkType-in @('Junction','SymbolicLink')){throw ('Redirected ART directory: '+$part)}}
        if($part.Equals($sdk,[StringComparison]::OrdinalIgnoreCase)){break}
    }
    if(Test-Path -LiteralPath $target){
        if(-not(Test-Path -LiteralPath $target -PathType Leaf)){throw ('ART target is a directory: '+$target)}
        # Reborn: a linked file is never eligible for legacy placeholder migration.
        if((Get-Item -LiteralPath $target -Force).LinkType-in @('Junction','SymbolicLink')){throw ('Redirected ART file: '+$target)}
        # Reborn: upgrade only the exact empty content generated by the previous script; preserve every other existing file.
        if((Get-Item -LiteralPath $target).Length-lt 200 -and [IO.File]::ReadAllText($target).Trim()-ceq $legacy){
            if($PSCmdlet.ShouldProcess($target,'Add EA namespace to exact legacy placeholder')){
                [IO.File]::WriteAllText($target,$content,[Text.UTF8Encoding]::new($false));$updated++
                [pscustomobject]@{Status='Updated';Reference=$reference;Path=$target}
            }else{[pscustomobject]@{Status='PreviewUpdate';Reference=$reference;Path=$target}}
            continue
        }
        $existing++;[pscustomobject]@{Status='Exists';Reference=$reference;Path=$target};continue
    }
    if($PSCmdlet.ShouldProcess($target,'Create empty AssetDeclaration placeholder')){
        $null=New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force
        # Reborn: CreateNew keeps a concurrently created real file intact; UTF-8 has no BOM and content is exactly the requested XML.
        $stream=[IO.File]::Open($target,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write,[IO.FileShare]::None)
        try{$bytes=[Text.UTF8Encoding]::new($false).GetBytes($content);$stream.Write($bytes,0,$bytes.Length)}finally{$stream.Dispose()}
        $created++;[pscustomobject]@{Status='Created';Reference=$reference;Path=$target}
    }else{[pscustomobject]@{Status='Preview';Reference=$reference;Path=$target}}
}
Write-Host ('Reborn: MISSINGART references={0}; created={1}; updated legacy placeholders={2}; already present={3}; skipped={4}.'-f $seen.Count,$created,$updated,$existing,$skipped)
